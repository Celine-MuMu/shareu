// 取字：t('check_items', { n: 18 }) → 「18 個物品」
function t(key, vars) {
  let s = (TEXT[currentLang] && TEXT[currentLang][key]) || TEXT.zh[key] || key;
  if (vars) {
    Object.keys(vars).forEach(function (k) {
      s = s.replace('{' + k + '}', vars[k]);
    });
  }
  return s;
}

// 取資料裡的雙語欄位：tr({ zh: '相機', en: 'Camera' }) → 依目前語言回傳
function tr(obj) {
  if (!obj || typeof obj === 'string') return obj || '';
  return obj[currentLang] || obj.zh;
}

// 把畫面上所有 data-i18n 的地方填上目前語言的字
function applyI18n(root) {
  (root || document).querySelectorAll('[data-i18n]').forEach(function (el) {
    el.textContent = t(el.dataset.i18n);
  });
  document.documentElement.lang = currentLang === 'zh' ? 'zh-Hant' : 'en';
}

// 切換語言，並記住
function setLang(lang) {
  currentLang = lang;
  try { localStorage.setItem('shareu-lang', lang); } catch (e) {}
}
